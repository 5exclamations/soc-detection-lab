"""Generate the detection catalog, ATT&CK mapping table and a Navigator layer from the rule files."""
from __future__ import annotations

import json
from collections import defaultdict

from .paths import DOCS_DIR, RULES_DIR, REPORTS_DIR
from . import attack
from .sigma import load_rules

TECHNIQUES = {t: v['name'] for t, v in attack.load_subset()['techniques'].items()}


def _rules():
    return sorted((r for r in load_rules(RULES_DIR).values() if r.alerting), key=lambda r: r.rule_id)


def catalog() -> str:
    out = ["# Detection Catalog", "", "_Generated by `python -m soclab docs` from `rules/*.yml`. Do not edit by hand._", "",
           "| ID | Title | Severity | Type | Techniques | Status |", "|---|---|---|---|---|---|"]
    rs = _rules()
    for r in rs:
        out.append(f"| {r.rule_id} | {r.title} | {r.level} | {r.kind} | {', '.join(r.techniques)} | {r.doc['status']} |")
    for r in rs:
        c = r.doc.get("correlation")
        logic = (f"{c['type']} over {c['rules']} grouped by {c.get('group-by')} within {c['timespan']}"
                 + (f", condition {c.get('condition')}" if c.get('condition') else "")) if c else "single-event Sigma selection"
        out += ["", f"## {r.rule_id} - {r.title}", "", r.doc["description"].strip(), "",
                f"- **Severity:** {r.level}" + (" (+1 if an `adm-`/root account is involved)" if r.ext.get("escalate_privileged") else ""),
                f"- **Logic:** {logic}", f"- **ATT&CK:** {', '.join(f'{t} {TECHNIQUES.get(t, "")}' for t in r.techniques)}; tactics: {', '.join(r.tactics)}",
                f"- **Known false positives:** " + "; ".join(r.doc["falsepositives"]),
                f"- **Tuning:** " + "; ".join(r.ext.get("tuning", [])),
                f"- **Limitations:** {r.ext['limitations']}", f"- **Runbook:** [{r.ext['runbook']}](../{r.ext['runbook']})",
                f"- **Source file:** `{r.path.relative_to(RULES_DIR.parent)}`"]
    return "\n".join(out) + "\n"


def mitre() -> str:
    by = defaultdict(list)
    for r in _rules():
        for t in r.techniques:
            by[t].append(r.rule_id)
    out = ["# ATT&CK Coverage", "", "_Generated. Mappings mean the rule is **relevant to** the technique, not that it fully covers it. "
           f"Validated against ATT&CK Enterprise v{attack.load_subset()['attack_version']} (see `python -m soclab attack-check`)._", "",
           "| Technique | Name | Rules |", "|---|---|---|"]
    out += [f"| {t} | {TECHNIQUES.get(t, '')} | {', '.join(v)} |" for t, v in sorted(by.items())]
    return "\n".join(out) + "\n"


def navigator() -> dict:
    by = defaultdict(list)
    for r in _rules():
        for t in r.techniques:
            by[t].append(r.rule_id)
    return {"name": "SOC lab coverage", "versions": {"attack": attack.attack_major(), "navigator": attack.NAVIGATOR_VERSION, "layer": attack.LAYER_VERSION},
            "domain": "enterprise-attack", "description": "Techniques with at least one lab detection",
            "techniques": [{"techniqueID": t, "score": len(v), "comment": ", ".join(v)} for t, v in sorted(by.items())]}


def write_all():
    (DOCS_DIR / "detection-catalog.md").write_text(catalog())
    (DOCS_DIR / "mitre-mapping.md").write_text(mitre())
    REPORTS_DIR.mkdir(exist_ok=True)
    (REPORTS_DIR / "attack-navigator-layer.json").write_text(json.dumps(navigator(), indent=2) + "\n")
